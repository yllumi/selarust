//! Build-time code generation for the **Sayagi Rust** PWA metaframework.
//!
//! `sayagi-build` is meant to be driven from a `build.rs`:
//!
//! ```no_run
//! fn main() {
//!     let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").unwrap();
//!     let out_dir = std::env::var("OUT_DIR").unwrap();
//!     sayagi_build::generate(manifest_dir, out_dir).unwrap();
//! }
//! ```
//!
//! A single run produces everything the app needs to be an installable PWA:
//!
//! * `$OUT_DIR/routes.rs` — the file-based route table plus the Leptos `<Routes>` tree.
//! * `$OUT_DIR/config.rs` — constants baked from `Sayagi.toml`.
//! * `<assets-dir>/manifest.webmanifest` — the web app manifest.
//! * `<assets-dir>/sw.js` — the generated service worker (cache strategies included).
//! * `<assets-dir>/icons/*.png` — maskable and regular app icons.

