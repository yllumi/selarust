/// Header stamped on every generated text file.
pub const GENERATED_HEADER: &str =
    "// @generated by sayagi-build. Do not edit by hand: run `cargo build` or `sayagi pwa`.";

/// Error type kept dependency-free on purpose (this crate runs inside `build.rs`).
#[derive(Debug)]
pub struct Error(String);

impl Error {
    pub(crate) fn new(message: impl Into<String>) -> Self {
        Self(message.into())
    }

    /// The human readable message.
    pub fn message(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

impl std::error::Error for Error {}

impl From<std::io::Error> for Error {
    fn from(error: std::io::Error) -> Self {
        Self(error.to_string())
    }
}

impl From<toml::de::Error> for Error {
    fn from(error: toml::de::Error) -> Self {
        Self(error.to_string())
    }
}

impl From<serde_json::Error> for Error {
    fn from(error: serde_json::Error) -> Self {
        Self(error.to_string())
    }
}

/// Convenience alias.
pub type Result<T> = std::result::Result<T, Error>;

/// What a generation run produced.
#[derive(Debug, Default, Clone)]
pub struct Report {
    /// Routes discovered under the pages directory.
    pub routes: Vec<Route>,
    /// Files (re)written by the generator.
    pub files: Vec<PathBuf>,
}

impl Report {
    /// One-line summary, handy for CLI output.
    pub fn summary(&self) -> String {
        format!(
            "{} route(s) and {} generated file(s)",
            self.routes.len(),
            self.files.len()
        )
    }
}

/// Reads `Sayagi.toml` from `manifest_dir`.
pub fn load_config(manifest_dir: impl AsRef<Path>) -> Result<Config> {
    Config::load(manifest_dir.as_ref())
}

/// Scans the pages directory described by `Sayagi.toml` and returns the route table.
pub fn scan_routes(manifest_dir: impl AsRef<Path>) -> Result<Vec<Route>> {
    let manifest_dir = manifest_dir.as_ref();
    let config = Config::load(manifest_dir)?;
    routes::scan(manifest_dir, &config)
}

/// Full generation: routes, config and every PWA asset.
pub fn generate(manifest_dir: impl AsRef<Path>, out_dir: impl AsRef<Path>) -> Result<Report> {
    let manifest_dir = manifest_dir.as_ref();
    let out_dir = out_dir.as_ref();
    let config = Config::load(manifest_dir)?;
    let discovered = routes::scan(manifest_dir, &config)?;

    let mut report = Report {
        routes: discovered.clone(),
        files: Vec::new(),
    };

    report.files.push(write_file(
        &out_dir.join("routes.rs"),
        &routes::codegen(&discovered),
    )?);
    report.files
        .push(write_file(&out_dir.join("config.rs"), &config::codegen(&config))?);

    let assets_dir = config.assets_dir(manifest_dir);
    std::fs::create_dir_all(&assets_dir)?;
    report.files.extend(pwa::write_manifest(&assets_dir, &config)?);
    report.files.extend(pwa::write_service_worker(&assets_dir, &config)?);
    report.files.extend(pwa::write_icons(&assets_dir, &config)?);

    println!("cargo:rerun-if-changed=Sayagi.toml");
    println!("cargo:rerun-if-changed={}", config.routes.dir.display());
    println!("cargo:rerun-if-changed={}", config.app.assets_dir.display());

    Ok(report)
}

/// Regenerates only the PWA assets (manifest, service worker, icons).
///
/// Used by `sayagi pwa`; `generate` already does this on every build.
pub fn generate_assets(manifest_dir: impl AsRef<Path>) -> Result<Report> {
    let manifest_dir = manifest_dir.as_ref();
    let config = Config::load(manifest_dir)?;
    let assets_dir = config.assets_dir(manifest_dir);
    std::fs::create_dir_all(&assets_dir)?;

    let mut report = Report::default();
    report.files.extend(pwa::write_manifest(&assets_dir, &config)?);
    report.files.extend(pwa::write_service_worker(&assets_dir, &config)?);
    report.files.extend(pwa::write_icons(&assets_dir, &config)?);
    Ok(report)
}

pub(crate) fn write_file(path: &Path, contents: &str) -> Result<PathBuf> {
    write_file_bytes(path, contents.as_bytes())?;
    Ok(path.to_path_buf())
}

pub(crate) fn write_file_bytes(path: &Path, contents: &[u8]) -> Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    // Skipping identical writes keeps Cargo from invalidating freshly built artifacts.
    if std::fs::read(path).map(|existing| existing == contents).unwrap_or(false) {
        return Ok(());
    }
    std::fs::write(path, contents)?;
    Ok(())
}

/// Escapes a string so it can be embedded in a generated Rust/JS string literal.
pub(crate) fn escape(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    for ch in value.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            other => out.push(other),
        }
    }
    out
}

/// Stable, dependency-free hash used to version generated assets.
pub(crate) fn fingerprint(parts: &[&str]) -> String {
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for part in parts {
        for byte in part.as_bytes() {
            hash ^= *byte as u64;
            hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
        }
        hash ^= 0xff;
        hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
    }
    format!("{:016x}", hash)
}
