//! Runtime primitives of the **Sayagi Rust** PWA metaframework.
//!
//! This crate is compiled twice: once for the Axum server (`ssr`) and once for the
//! Wasm client that hydrates it (`hydrate`). It provides the pieces an app would
//! otherwise hand-roll for every project:
//!
//! * [`MobileLayout`], [`HeaderBar`], [`BottomNav`], [`LinkButton`] and [`PullToRefresh`] — the mobile UI shell.
//! * [`BottomSheet`] (drag/tap/`Escape` to dismiss) and the edge swipe-back gesture of
//!   [`MobileLayout`], with thresholds exposed as [`SWIPE_BACK_EDGE`],
//!   [`SWIPE_BACK_TRIGGER`] and [`SHEET_DISMISS_RATIO`].
//! * [`param`] — typed access to `[id]`-style route parameters.
//! * [`register_service_worker`] and [`watch_connectivity`] — PWA wiring.
//! * [`RouteInfo`] — the route table generated by `sayagi-build`.
//! * [`offline`] and [`sync`] — offline storage and realtime sync plumbing.
//! * [`note_route_depth`] — transition direction (slide/fade) derived from route depth.

mod components;
