/// The flavour of a generated route.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RouteKind {
    /// Only literal segments, e.g. `/dashboard`.
    Static,
    /// Contains at least one `[param]` segment, e.g. `/containers/:id`.
    Dynamic,
    /// Ends with a `[...rest]` catch-all, e.g. `/files/*path`.
    Wildcard,
}

impl RouteKind {
    /// Lowercase label, useful for debugging UIs.
    pub fn label(self) -> &'static str {
        match self {
            RouteKind::Static => "static",
            RouteKind::Dynamic => "dynamic",
            RouteKind::Wildcard => "wildcard",
        }
    }
}

/// Metadata for one route discovered under `src/pages` at build time.
///
/// The table itself is generated into `ROUTES` by `sayagi-build`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct RouteInfo {
    /// leptos_router path pattern, e.g. `/containers/:id`.
    pub path: &'static str,
    /// Source file relative to the app root.
    pub file: &'static str,
    /// Generated module name.
    pub module: &'static str,
    /// Static, dynamic or wildcard.
    pub kind: RouteKind,
}

impl RouteInfo {
    /// Lowercase flavour label.
    pub fn label(&self) -> &'static str {
        self.kind.label()
    }
}

